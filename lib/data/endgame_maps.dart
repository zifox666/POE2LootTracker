List<EndgameMapOption> mapOptionsForAliases(Iterable<String> aliases) {
  final values = aliases.map((value) => value.toLowerCase()).toSet();
  return [
    for (final option in endgameMaps)
      if (option.aliases.any((name) => values.contains(name.toLowerCase())))
        option,
  ];
}

Set<String> aliasesForMapKeys(Iterable<String> keys) {
  final selected = keys.toSet();
  return {
    for (final option in endgameMaps)
      if (selected.contains(option.key)) ...option.aliases,
  };
}
